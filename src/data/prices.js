// Единый вид сумм: разряды от 1000 разделяются неразрывным пробелом, «₽» не отрывается от числа. Сами значения не меняются.
export const money = (s) => String(s)
  .replace(/(\d)[  ](?=\d{3}(?!\d))/g, '$1')
  .replace(/\d{4,}/g, (n) => n.replace(/\B(?=(\d{3})+$)/g, ' '))
  .replace(/ ₽/g, ' ₽')
